// mediabase / scripts / gen-client-roster.mjs — the browser roster, generated.
//
// The host composes from DATA (patch layers); the page must compose from data too, but a
// browser bundle needs STATIC imports — a runtime lookup of `@mediabase/ui-web` cannot be
// bundled by Vite. So the roster file (`packages/bundle/ui/client.yml`) is the source of
// truth and this script turns it into `apps/web/src/roster.generated.ts`.
//
// Run:  node scripts/gen-client-roster.mjs           # rewrite the generated module
//       node scripts/gen-client-roster.mjs --check   # fail if it is stale (pnpm test runs this)
//
// A stale generated file is the failure mode worth guarding: a roster edit that is not
// regenerated would leave the page composing the OLD set while the file on disk says
// otherwise — green tests, wrong app.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as yaml from 'js-yaml'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
/** The app that composes the roster owns the bundles it composes. */
const WEB_MANIFEST = join(ROOT, 'apps/web/package.json')
const OUT = join(ROOT, 'apps/web/src/roster.generated.ts')

/** The UI bundle's directory, resolved from the web app (the same rule the host uses). */
export function uiBundleDir() {
  const require = createRequire(WEB_MANIFEST)
  return dirname(require.resolve('@mediabase/bundle-ui/package.json'))
}

/** The roster entries, in mount order. */
export function readRoster() {
  const dir = uiBundleDir()
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const rosterFile = join(dir, manifest.mediabase?.uiBundle?.roster ?? manifest.avstudio?.uiBundle?.roster ?? 'client.yml')
  if (!existsSync(rosterFile)) throw new Error(`gen-client-roster: roster 文件不存在: ${rosterFile}`)
  const rows = yaml.load(readFileSync(rosterFile, 'utf8'))
  if (!Array.isArray(rows)) throw new Error(`gen-client-roster: ${rosterFile} 顶层必须是数组`)
  return rows.map((row) => {
    if (row === null || typeof row !== 'object' || typeof row.id !== 'string' || typeof row.name !== 'string') {
      throw new Error(`gen-client-roster: 每一行都需要 id 与 name,收到: ${JSON.stringify(row)}`)
    }
    const out = { id: row.id, name: row.name }
    if (row.config !== undefined) {
      if (row.config === null || typeof row.config !== 'object' || Array.isArray(row.config)) {
        throw new Error(`gen-client-roster: 行 ${row.id} 的 config 必须是对象`)
      }
      out.config = row.config
    }
    return out
  })
}

/** The module the page imports: static imports, so Vite bundles exactly the roster. */
export function renderRoster(rows) {
  const imports = rows.map((row, index) => `import * as plugin${index} from '${row.name}'`)
  const entries = rows.map((row, index) => {
    const config = row.config === undefined ? '' : `, config: ${JSON.stringify(row.config)}`
    return `  { id: '${row.id}', name: '${row.name}', plugin: plugin${index} as ClientPlugin${config} },`
  })
  return `${[
    '// GENERATED by scripts/gen-client-roster.mjs — do not edit.',
    '// Source of truth: packages/bundle/ui/client.yml (the UI bundle\'s roster).',
    '//',
    '// The page composes from data like the host does, but a browser bundle needs static',
    '// imports, so the roster is generated here and `pnpm run build:web` regenerates it.',
    '// `pnpm test` fails when this file is stale.',
    '',
    "import type { Plugin } from '@deepseek-ai/cordis'",
    ...imports,
    '',
    '/** A client plugin module, as the roster names it. */',
    'export type ClientPlugin = Plugin.Object',
    '',
    '/** One roster row: optional config is passed to `ctx.plugin` (e.g. shell title). */',
    'export type ClientRosterEntry = { id: string; name: string; plugin: ClientPlugin; config?: Record<string, unknown> }',
    '',
    '/** The browser roster in MOUNT ORDER: registries first, the shell last. */',
    'export const CLIENT_ROSTER: ReadonlyArray<ClientRosterEntry> = [',
    ...entries,
    ']',
    '',
  ].join('\n')}`
}

const rows = readRoster()
const rendered = renderRoster(rows)
const check = process.argv.includes('--check')
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''

if (check) {
  if (current !== rendered) {
    console.error(
      `gen-client-roster: ${relative(ROOT, OUT)} 与 packages/bundle/ui/client.yml 不一致 ——`
      + ' 运行 `node scripts/gen-client-roster.mjs` 重新生成。',
    )
    process.exitCode = 1
  } else {
    console.log(`gen-client-roster: 已是最新(${rows.length} 个客户端插件)。`)
  }
} else if (current === rendered) {
  console.log(`gen-client-roster: 无需改动(${rows.length} 个客户端插件)。`)
} else {
  writeFileSync(OUT, rendered)
  console.log(`gen-client-roster: 已写入 ${relative(ROOT, OUT)}(${rows.length} 个客户端插件)。`)
}
